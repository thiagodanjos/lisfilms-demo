export const feed: FeedItem[] = reviews
  .slice()
  .sort((a, b) => (a.date < b.date ? 1 : -1))
  .map((r) => ({
    id: `f-${r.id}`,
    userId: r.userId,
    mediaId: r.mediaId,
    reviewId: r.id,
    kind: 'review' as const,
    date: r.date,
  }))

export function mediaById(id: string): Media | undefined {
  return media.find((m) => m.id === id)
}

export function userById(id: string): DemoUser | undefined {
  return users.find((u) => u.id === id)
}

export function reviewsForMedia(mediaId: string): Review[] {
  return reviews.filter((r) => r.mediaId === mediaId).sort((a, b) => (a.date < b.date ? 1 : -1))
}

export function reviewsByUser(userId: string): Review[] {
  return reviews.filter((r) => r.userId === userId).sort((a, b) => (a.date < b.date ? 1 : -1))
}

